const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const crypto=require('node:crypto');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const data=JSON.parse(fs.readFileSync(root+'/colliders.json','utf8'));
 const {createCollisionWorld}=await import(pathToFileURL(root+'/viewer/collision.mjs'));
 const world=createCollisionWorld(data);
 assert.deepEqual(data.player.spawn,[2,1.65,-.7]);
 const start=world.safeSpawn(data.player.spawn);
 const corridor=world.move(start,0,-6.3);
 assert(Math.abs(corridor.x-2)<1e-6&&Math.abs(corridor.z+7)<1e-6,'El pasillo x2 debe estar libre desde y0.7 hasta y7.');
 const street=world.move(start,0,8.7);
 assert(Math.abs(street.x-2)<1e-6&&Math.abs(street.z-8)<1e-6,'La salida al frente y la calle deben estar libres.');
 const glb=fs.readFileSync(root+'/colmado-el-bloke.glb');
 const jsonLength=glb.readUInt32LE(12);const gltf=JSON.parse(glb.subarray(20,20+jsonLength).toString());
 assert.equal((gltf.skins??[]).length,0,'La escena no debe incluir personajes articulados.');
 assert.equal((gltf.animations??[]).length,0,'La escena no debe incluir la animacion del personaje.');
 const tileNodes=gltf.nodes.filter(o=>/^Ficha\b/i.test(o.name??''));
 assert.equal(tileNodes.length,0,'La mesa no debe tener fichas.');
 console.log('WORLD PASS',JSON.stringify({spawn:data.player.spawn,corridor,street,colliders:world.boxCount,skins:0,tileNodes:0}));
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox']});
 const errors=[];
 const context=await browser.newContext({viewport:{width:1200,height:800},deviceScaleFactor:1});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 page.on('console',msg=>{if(msg.type()==='error'&&!msg.text().includes('404'))errors.push(msg.text());});
 const baseURL=process.env.COLMADO_PREVIEW_URL||'http://127.0.0.1:8765/viewer/';
 const url=baseURL+'?sixTables='+Date.now();
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.colmadoPreview?.ready,null,{timeout:120000});
 await page.waitForFunction(()=>getComputedStyle(document.getElementById('loading')).opacity==='0',null,{timeout:10000});
 const loaded=await page.evaluate(()=>({x:colmadoPreview.camera.position.x,y:colmadoPreview.camera.position.y,z:colmadoPreview.camera.position.z,colliders:colmadoPreview.world.boxCount}));
 assert.deepEqual(loaded,{x:2,y:1.65,z:-.7,colliders:world.boxCount});
 await page.screenshot({path:root+'/viewer-desktop.png',timeout:120000});
 const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const mp=await mobile.newPage();mp.on('pageerror',e=>errors.push(e.message));
 await mp.goto(url,{waitUntil:'domcontentloaded'});
 await mp.waitForFunction(()=>window.colmadoPreview?.ready,null,{timeout:120000});
 await mp.waitForFunction(()=>getComputedStyle(document.getElementById('loading')).opacity==='0',null,{timeout:10000});
 assert(await mp.locator('#pad').isVisible());
 await mp.screenshot({path:root+'/viewer-mobile.png',timeout:120000});
 assert.equal(errors.length,0,errors.join('\n'));
 const report={version:'six-tables-24-chairs',sourceSHA256:crypto.createHash('sha256').update(glb).digest('hex'),spawn:data.player.spawn,corridor,street,colliders:world.boxCount,skins:0,tileNodes:0,errors,captures:['viewer-desktop.png','viewer-mobile.png']};
 fs.writeFileSync(root+'/viewer/six-tables-check.json',JSON.stringify(report,null,2));
 console.log('BROWSER PASS',JSON.stringify(loaded));
 console.log('PASS: nueva disposicion, pasillo, calle, altura fija, escritorio y movil sin errores');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
