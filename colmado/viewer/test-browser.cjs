const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const assetRoot=path.resolve(__dirname,'..');
const previewURL=process.env.COLMADO_PREVIEW_URL||'http://127.0.0.1:8765/viewer/';
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox']});
 const context=await browser.newContext({viewport:{width:800,height:600},deviceScaleFactor:1});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
 await page.goto(previewURL,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.colmadoPreview?.ready,null,{timeout:120000});
 await page.waitForTimeout(1500);
 const initial=await page.evaluate(()=>({x:colmadoPreview.camera.position.x,y:colmadoPreview.camera.position.y,z:colmadoPreview.camera.position.z,meshes:colmadoPreview.scene.children[4]?.children.length,loaded:colmadoPreview.ready,boxCount:colmadoPreview.world.boxCount}));
 assert(initial.loaded);
 assert.equal(initial.y,1.65);
 console.log('LOADED',JSON.stringify(initial));
 await page.screenshot({path:path.join(assetRoot,'viewer-desktop.png'),timeout:120000});
 await page.keyboard.down('KeyA');await page.waitForFunction(startX=>Math.abs(colmadoPreview.camera.position.x-startX)>.1,initial.x,{timeout:10000});await page.keyboard.up('KeyA');
 const after=await page.evaluate(()=>({x:colmadoPreview.camera.position.x,y:colmadoPreview.camera.position.y,z:colmadoPreview.camera.position.z}));
 assert(Math.hypot(after.x-initial.x,after.z-initial.z)>.1,'A debe mover la cámara');
 assert.equal(after.y,initial.y);
 console.log('KEYBOARD',JSON.stringify(after));
 const boundary=await page.evaluate(()=>{
  const p=window.colmadoPreview;
  const far=p.world.move({x:p.camera.position.x,z:p.camera.position.z},0,1000);
  return {...far,free:p.world.isFree(far.x,far.z),maxZ:p.world.bounds.maxZ};
 });
 assert(boundary.z<=boundary.maxZ);
 assert(boundary.free);
 console.log('BOUNDARY',JSON.stringify(boundary));
 await page.click('#reset');
 const yawBefore=await page.evaluate(()=>colmadoPreview.camera.rotation.y);
 await page.mouse.move(400,300);await page.mouse.down();await page.mouse.move(540,330,{steps:5});await page.mouse.up();
 await page.waitForTimeout(200);
 const yawAfter=await page.evaluate(()=>colmadoPreview.camera.rotation.y);
 assert(Math.abs(yawAfter-yawBefore)>.1,'Arrastrar debe girar la vista');
 console.log('LOOK',JSON.stringify({yawBefore,yawAfter}));
 await page.click('#reset');
 assert.deepEqual(await page.evaluate(()=>({x:colmadoPreview.camera.position.x,y:colmadoPreview.camera.position.y,z:colmadoPreview.camera.position.z})),{x:initial.x,y:initial.y,z:initial.z});
 const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const mp=await mobile.newPage();
 mp.on('pageerror',e=>errors.push(e.message));
 await mp.goto(previewURL,{waitUntil:'domcontentloaded'});
 await mp.waitForFunction(()=>window.colmadoPreview?.ready,null,{timeout:120000});
 await mp.waitForTimeout(500);
 assert(await mp.locator('#pad').isVisible());
 assert(await mp.locator('#touch-guide').isVisible());
 const mobileStart=await mp.evaluate(()=>({x:colmadoPreview.camera.position.x,z:colmadoPreview.camera.position.z}));
 const leftButton=await mp.locator('[data-move=left]').boundingBox();
 const cdp=await mobile.newCDPSession(mp);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:leftButton.x+leftButton.width/2,y:leftButton.y+leftButton.height/2}]});
 await mp.waitForFunction(start=>Math.abs(colmadoPreview.camera.position.x-start)>.05,mobileStart.x,{timeout:10000});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 const mobileAfter=await mp.evaluate(()=>({x:colmadoPreview.camera.position.x,y:colmadoPreview.camera.position.y,z:colmadoPreview.camera.position.z}));
 assert(Math.hypot(mobileAfter.x-mobileStart.x,mobileAfter.z-mobileStart.z)>.05,'La cruceta debe mover la camara con un toque sostenido');
 assert.equal(mobileAfter.y,1.65);
 console.log('TOUCH',JSON.stringify(mobileAfter));
 await mp.click('#reset');
 await mp.screenshot({path:path.join(assetRoot,'viewer-mobile.png'),timeout:120000});
 console.log('MOBILE',JSON.stringify(await mp.evaluate(()=>({width:innerWidth,height:innerHeight,ready:colmadoPreview.ready}))));
 const realErrors=errors.filter(s=>!s.includes('favicon.ico')&&!s.includes('404 (File not found)'));
 assert.equal(realErrors.length,0,realErrors.join('\n'));
 console.log('PASS desktop carga, teclado, altura, limites, arrastre, reset y movil sin errores JS');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
